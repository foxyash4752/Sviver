[BITS 16] ; Включаем процессор на 16 битный режим
[ORG 0x7C00] ; Кладём первый сектор диска по адресу 0x7C00

start: ; Создаём метку start
    cli ; Выключаем прерывания процессора
    xor ax, ax ; Обнуляем регистр ax
    mov ds, ax ; Обнуляем сегмент Data
    mov es, ax ; Обнуляем сегмент Extra
    mov ss, ax ; Обнуляем сегмент Stack
    mov sp, 0x9000 ; Создаём верхушку стека
    mov [boot_drive], dl ; Сохраняем номер диска
    sti ; Включаем прерывания процессора

    mov ah, 0x02 ; Создаём вторую функцию чтения секторов
    mov al, 17 ; Задаём колличество секторов
    mov ch, 0 ; Задаём цилиндр (дорожку) 0
    mov cl, 2 ; Начинаем со второго сектора
    mov dh, 0 ; Задаём головку (сторону дискеты) 0
    mov dl, [boot_drive] ; Задаём диск чтения
    mov bx, 0x1000 ; 
    mov es, bx ; 
    xor bx, bx ; 
    int 0x13 ; 
    jc hang ; 

    cli ; 
    lgdt [gdt_desc] ; 
    mov eax, cr0 ; 
    or eax, 1 ; 
    mov cr0, eax ; 
    jmp 0x08:pm_start ; 

[BITS 32]
pm_start:
    mov ax, 0x10     ; селектор сегмента данных из GDT
    mov ds, ax       ; перезагружаем ВСЕ сегментные регистры,
    mov es, ax       ; иначе они остались с мусором из real mode
    mov fs, ax
    mov gs, ax
    mov ss, ax
    jmp 0x10000      ; ВСЁ: прыгаем в начало нашего C-ядра!

[BITS 16]
hang:
    jmp $            ; $ = текущий адрес → бесконечный цикл «авария»

; --- GDT: таблица, описывающая сегменты для 32 бит ---
gdt_start:
    dq 0             ; дескриптор 0: ОБЯЗАН быть нулём (null-дескриптор)
gdt_code:            ; дескриптор 1 → селектор 0x08: КОД
    dw 0xFFFF        ; лимит (младшие 16 бит)
    dw 0x0000        ; база (младшие 16 бит)
    db 0x00          ; база (средние 8 бит)
    db 10011010b     ; доступ: present, ring 0, код, исполняемый, читаемый
    db 11001111b     ; гранулярность: 4КБ + 32-битный режим (бит DB) + лимит старший
    db 0x00          ; база (старшие 8 бит)  → база 0, лимит 4 ГБ
gdt_data:            ; дескриптор 2 → селектор 0x10: ДАННЫЕ
    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 10010010b     ; доступ: present, ring 0, данные, читаемый/писаемый
    db 11001111b
    db 0x00
gdt_end:

gdt_desc:
    dw gdt_end - gdt_start - 1  ; размер GDT минус 1 (так требует процессор)
    dd gdt_start                ; адрес GDT в памяти

times 510-($-$$) db 0  ; добиваем файл нулями ровно до 510 байт
dw 0xAA55              ; байты 510–511: подпись «я загрузочный сектор!»
boot_drive db 0        ; (nasm положит это... см. ниже!)